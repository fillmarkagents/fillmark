// Writes src/generated/ from the repo: contract ABIs from the forge build output (run
// `forge build` at the repo root first) and the asset list from assets.json.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { getAddress } from "viem";

const root = new URL("../../", import.meta.url);
const read = (path: string) => JSON.parse(readFileSync(new URL(path, root), "utf8"));
const abiOf = (name: string) => read(`out/${name}.sol/${name}.json`).abi;

const header = "// Generated by scripts/gen.ts. Do not edit.\n\n";
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true });
writeFileSync(
  new URL("../src/generated/abi.ts", import.meta.url),
  header +
    `export const routerAbi = ${JSON.stringify(abiOf("FillmarkRouterV3"), null, 2)} as const;\n\n` +
    `export const feedsAbi = ${JSON.stringify(abiOf("FillmarkFeeds"), null, 2)} as const;\n\n` +
    `export const payAbi = ${JSON.stringify(abiOf("FillmarkPay"), null, 2)} as const;\n`,
);

type Entry = { ticker: string; token: string; decimals: number };
const assets = read("assets.json") as { stocks: Entry[]; crypto: Entry[] };
const list = [
  ...assets.stocks.map((a) => ({ ticker: a.ticker, token: getAddress(a.token), decimals: a.decimals, crypto: false })),
  ...assets.crypto.map((a) => ({ ticker: a.ticker, token: getAddress(a.token), decimals: a.decimals, crypto: true })),
];
writeFileSync(
  new URL("../src/generated/assets.ts", import.meta.url),
  header +
    "// Tokens the Fillmark feeds price, from assets.json. A hint only: the router's pools and the\n" +
    "// feeds are read from chain.\n" +
    `export const ASSET_LIST = ${JSON.stringify(list, null, 2)} as const;\n`,
);
console.log(`abi and ${list.length} assets written`);
